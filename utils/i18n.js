  let lang = 'en'
  function setLang(l) { lang = DICT[l] || l === 'en' ? l : 'en' }
  function getLang() { return lang }

  const fill = (s, vars) => vars ? s.replace(/\{(\w+)\}/g, (m, k) => vars[k] != null ? vars[k] : m) : s
  // t('Registered {date}', { date }) -> text in the current language
  function t(key, vars, l) {
    l = l || lang
    const d = DICT[l]
    return fill((d && d[key]) || key, vars)
  }
  // Count with the right English singular/plural key: plural(3, 'product') -> "3 products" / "3 alaab" / "3 个产品"
  function plural(n, word, l) { return t('{n} ' + word + (n === 1 ? '' : 's'), { n }, l) }

  // ---- translating text that was already built in English (web app) ----
  const esc = s => s.replace(/[.*+?^$()|[\]\\]/g, '\\$&')
  const NUM = { n: 1, a: 1, b: 1, size: 1 } // placeholders that are always numbers
  let patterns = null
  function compile() {
    patterns = T.filter(r => /\{\w+\}/.test(r[0])).map(r => {
      const names = []
      const src = esc(r[0]).replace(/\\?\{(\w+)\\?\}/g, (m, k) => { names.push(k); return NUM[k] ? '([\\d.,]+)' : '(.+?)' })
      return { re: new RegExp('^' + src + '$'), names, key: r[0], dot: r[0].indexOf(' · ') >= 0 }
    }).sort((a, b) => b.key.length - a.key.length)
  }
  function translate(text, l, depth) {
    l = l || lang
    if (l === 'en' || !text) return text
    const d = DICT[l]
    if (d[text] != null) return d[text]
    depth = depth || 0
    if (depth > 3) return text
    if (!patterns) compile()
    // "a · b · c" is translated part by part, unless a whole pattern has " · " in it
    const dotted = text.indexOf(' · ') > 0
    for (const p of patterns) {
      if (dotted && !p.dot) continue
      const m = p.re.exec(text)
      if (m) {
        const vars = {}
        p.names.forEach((k, i) => { vars[k] = translate(m[i + 1], l, depth + 1) })
        return fill(d[p.key], vars)
      }
    }
    if (dotted) return text.split(' · ').map(x => translate(x, l, depth + 1)).join(' · ')
    return text
  }

  // Dictionary for the mini program templates: { 'English': 'translated' }
  function table(l) {
    l = l || lang
    const out = {}
    T.forEach(r => { out[r[0]] = l === 'so' ? r[1] : l === 'zh' ? r[2] : r[0] })
    return out
  }

  return { LANGS, t, plural, translate, setLang, getLang, table, MONTHS, keys: () => T.map(r => r[0]) }
